func assertDestinationMetadataDetailsResponse(t *testing.T, response metadata.DestinationMetadataResponse) {
	testutils.AssertEqual(t, response.Code, "Success")

	data := response.Data.DestinationMetadata
	testutils.AssertEqual(t, data.ID, "snowflake")
	testutils.AssertEqual(t, data.Name, "Snowflake")
	testutils.AssertEqual(t, data.Type, "Warehouse")
	testutils.AssertEqual(t, data.Description, "Snowflake is a cloud data warehouse")
	testutils.AssertEqual(t, data.IconURL, "https://fivetran.com/integrations/snowflake/resources/snowflake.png")
	testutils.AssertEqual(t, len(data.Icons), 2)
	testutils.AssertEqual(t, data.LinkToDocs, "https://fivetran.com/docs/destinations/snowflake")
	testutils.AssertEqual(t, data.ServiceStatus, "general_availability")
	testutils.AssertEqual(t, data.ServiceStatusUpdatedAt, "2022-01-13")

	testutils.AssertEqual(t, len(data.SupportedRegions), 2)
	testutils.AssertEqual(t, data.SupportedRegions[0], "GCP_US_EAST4")
	testutils.AssertEqual(t, data.SupportedRegions[1], "AWS_US_EAST_1")
	testutils.AssertEqual(t, data.SupportsHybridDeployment, false)
	testutils.AssertEqual(t, data.SupportsPrivateLink, true)
	testutils.AssertEqual(t, len(data.PrivateLinkTypes), 2)
	testutils.AssertEqual(t, data.PrivateLinkTypes[0], "SELF_SERVICE")
	testutils.AssertEqual(t, data.PrivateLinkTypes[1], "CUSTOMER_MANAGED")
	testutils.AssertEqual(t, len(data.SupportedNetworkingMethods), 3)
	testutils.AssertEqual(t, data.SupportedNetworkingMethods[0], "Directly")

	testutils.AssertEqual(t, data.Config.Type, "object")
	testutils.AssertEqual(t, data.Config.Title, "Snowflake config object")
	testutils.AssertEqual(t, len(data.Config.Required), 2)
	testutils.AssertEqual(t, data.Config.Required[0], "host")

	host := data.Config.Properties["host"]
	if host == nil {
		t.Fatal("expected the host property to be present")
	}
	testutils.AssertEqual(t, host.Type, "string")
	testutils.AssertEqual(t, host.FieldStatus, "general_availability")

	database := data.Config.Properties["database"]
	if database == nil {
		t.Fatal("expected the database property to be present")
	}
	testutils.AssertEqual(t, database.Immutable, true)

	password := data.Config.Properties["password"]
	if password == nil {
		t.Fatal("expected the password property to be present")
	}
	testutils.AssertEqual(t, password.Format, "password")

	publicKey := data.Config.Properties["public_key"]
	if publicKey == nil {
		t.Fatal("expected the public_key property to be present")
	}
	testutils.AssertEqual(t, publicKey.Readonly, true)

	auth := data.Config.Properties["auth"]
	if auth == nil {
		t.Fatal("expected the auth property to be present")
	}
	testutils.AssertEqual(t, len(auth.Enum), 2)
	testutils.AssertEqual(t, auth.Enum[0], "PASSWORD")

	nested := data.Config.Properties["nested"]
	if nested == nil || nested.Properties["inner"] == nil {
		t.Fatal("expected the nested.inner property to be present")
	}
	testutils.AssertEqual(t, nested.Properties["inner"].Type, "string")

	if data.ExternalSecretsKeysConfig == nil {
		t.Fatal("expected external_secrets_keys_config to be present")
	}
	testutils.AssertEqual(t, data.ExternalSecretsKeysConfig.Properties["password_key"].Type, "string")
}

func TestDestinationMetadataDetailsServiceOmitsExternalSecretsKeysConfig(t *testing.T) {
	// arrange
	ftClient, mockClient := testutils.CreateTestClient()
	mockClient.When(http.MethodGet, "/v1/metadata/destination-types/snowflake").
		ThenCall(func(req *http.Request) (*http.Response, error) {
			body := `{"code": "Success", "data": {"id": "snowflake", "config": {"type": "object"}}}`
			return mock.NewResponse(req, http.StatusOK, body), nil
		})

	// act
	response, err := ftClient.NewDestinationMetadataDetails().
		Service("snowflake").
		Do(context.Background())

	// assert
	if err != nil {
		t.Error(err)
	}
	if response.Data.ExternalSecretsKeysConfig != nil {
		t.Error("expected external_secrets_keys_config to be nil when the API omits it")
	}
}
